# Crea un programa que pida al usuario 
# dos palabras y le diga si son iguales 
# o no lo son.

palabra1 = input("Dime una palabra: ")
palabra2 = input("Dime otra palabra: ")

if palabra1 == palabra2:
    print("Son iguales")
else:
    print("No son iguales")

if palabra1 != palabra2:
    print("No son iguales")
else:
    print("Son iguales")
